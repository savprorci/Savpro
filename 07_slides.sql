-- ÉTAPE 7 : slides de l'accueil modifiables par l'administrateur (texte, image ou vidéo)
-- Prérequis : étape 4 (v2) déjà lancée. Peut être relancé sans risque.

create table if not exists public.slides (
  id           bigint generated by default as identity primary key,
  position     integer not null default 0,
  title        text    not null default '',
  body         text    not null default '',
  media_type   text    not null default 'produit' check (media_type in ('produit','image','video')),
  media_url    text,
  product_ref  text,
  cta_label    text,
  cta_page     text    default 'shop',
  active       boolean not null default true,
  updated_at   timestamptz not null default now()
);

drop trigger if exists slides_touch on public.slides;
create trigger slides_touch before update on public.slides
for each row execute function public.touch_updated_at();

alter table public.slides enable row level security;

drop policy if exists "slides lecture" on public.slides;
create policy "slides lecture" on public.slides
  for select to anon, authenticated using (active or public.is_admin());

drop policy if exists "slides gestion admin" on public.slides;
create policy "slides gestion admin" on public.slides
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

grant select on public.slides to anon;
grant select, insert, update, delete on public.slides to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Journal d'activité
drop trigger if exists audit_slides on public.slides;
create trigger audit_slides after insert or update or delete on public.slides
for each row execute function public.audit_trigger();

-- Stockage des images et vidéos des slides (public en lecture, écriture admin)
insert into storage.buckets (id, name, public)
values ('slides', 'slides', true)
on conflict (id) do nothing;

drop policy if exists "slides médias admin" on storage.objects;
create policy "slides médias admin" on storage.objects
  for all to authenticated
  using (bucket_id = 'slides' and public.is_admin())
  with check (bucket_id = 'slides' and public.is_admin());

